export type Locale = 'pt-BR' | 'en-US' | 'es-ES'

const LOCALE_KEY = 'todo-list:locale'
const SUPPORTED_LOCALES: Locale[] = ['pt-BR', 'en-US', 'es-ES']

function normalizeLocale(value?: string | null): Locale {
  if (value && SUPPORTED_LOCALES.includes(value as Locale)) {
    return value as Locale
  }

  const browserLocale = value?.toLowerCase() ?? ''

  if (browserLocale.startsWith('pt')) return 'pt-BR'
  if (browserLocale.startsWith('es')) return 'es-ES'
  return 'en-US'
}

